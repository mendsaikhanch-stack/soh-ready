-- Айл тус бүрийн сарын хураамж (ялгавартай тариф)
--
-- Учир нь: зарим СӨХ тоот бүрээр өөр тариф тогтоодог — эхний давхрууд өөр,
-- дээшээ өөр, албан байгууллагын тоот бас өөр (жишээ: Хөгжил хаус СӨХ #2681).
-- Өмнө нь зөвхөн sokh_organizations.monthly_fee (СӨХ-д НЭГ дүн) байсан тул
-- нэхэмжлэх үүсгэхэд бүх айлд ижил дүн бичигдэж байсан.
--
-- NULL = "энэ айлд тусгай тариф алга" → СӨХ-ийн ерөнхий monthly_fee хэрэглэнэ.
-- Тиймээс энэ багана нь одоо байгаа бүх СӨХ-ийн ажиллагаанд нөлөөлөхгүй.

ALTER TABLE residents ADD COLUMN IF NOT EXISTS monthly_fee NUMERIC;

COMMENT ON COLUMN residents.monthly_fee IS
  'Тухайн айлын сарын хураамж. NULL бол sokh_organizations.monthly_fee-г хэрэглэнэ.';
