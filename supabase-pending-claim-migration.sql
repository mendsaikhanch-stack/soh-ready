-- Өөрөө бүртгүүлсэн оршин суугчийг дарга баталгаажуулах хүртэл "хүлээгдэж буй"
--
-- Учир нь: /api/auth/register нь ямар ч тохиолдолд residents-д ШИНЭ мөр
-- нэмдэг байсан. Тиймээс даргын импортолсон жагсаалтад аль хэдийн байгаа айл
-- өөр утсаар бүртгүүлбэл тэр тоот ХОЁР мөр болж, айлын тоо ба нийт дүн
-- буруу гардаг байв.
--
-- Одоо: тухайн СӨХ-д ижил тоот эзэнгүй (auth_user_id NULL) байвал шинэ мөр
-- үүсгэхгүй, байгаа мөрийг нь холбоно. Холбох боломжгүй тохиолдолд шинэ мөр
-- үүсгэх ч pending_claim = TRUE тэмдэгтэй болж, дарга баталгаажуулах хүртэл
-- айлын тоо/нийт дүнд ОРОХГҮЙ.
--
-- FALSE = энгийн, баталгаатай мөр. Одоо байгаа бүх мөр FALSE болно —
-- тиймээс энэ багана хуучин өгөгдөлд нөлөөлөхгүй.

ALTER TABLE residents
  ADD COLUMN IF NOT EXISTS pending_claim BOOLEAN NOT NULL DEFAULT FALSE;

COMMENT ON COLUMN residents.pending_claim IS
  'Өөрөө бүртгүүлсэн боловч дарга хараахан баталгаажуулаагүй мөр. TRUE бол тоо/дүнд оруулахгүй.';

-- Даргын самбар эдгээрийг эхэнд шүүдэг тул индекс
CREATE INDEX IF NOT EXISTS residents_pending_claim_idx
  ON residents (sokh_id) WHERE pending_claim;
