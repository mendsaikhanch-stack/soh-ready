-- Маркетинг: кампанит ажлыг группийн төрлөөр чиглүүлэх
-- =====================================================
-- Supabase SQL Editor дотор ГАР аргаар ажиллуулна.
--
-- Яагаад: өмнө нь өдрийн дараалал НЭГ кампанит ажил сонгоод (хамгийн сүүлд
-- шинэчилсэн нь) бүх группэд ижил текст тавьдаг байсан. Тиймээс СӨХ-ийн дарга
-- нарын группэд оршин суугчид зориулсан пост очих эрсдэлтэй байв.
--
-- Одоо кампанит ажил бүр «хэнд зориулсан» гэдгээ зарлана. Дараалал үүсэх үед
-- групп бүрд тохирох кампанит ажлуудаас сонгоно.
--
--   target_types = NULL эсвэл хоосон  →  бүх төрөлд тохирно (ерөнхий текст,
--                                        группийн төрлөөр дэгээ/CTA нэмнэ)
--   target_types = {'hoa_mgmt'}       →  зөвхөн СӨХ-ийн дарга нарын группэд,
--                                        текстийг ХЭВЭЭР нь ашиглана
--
-- Боломжит утга: hoa_mgmt | resident | apartment | general

ALTER TABLE marketing_campaigns
  ADD COLUMN IF NOT EXISTS target_types text[];

COMMENT ON COLUMN marketing_campaigns.target_types IS
  'Аль төрлийн группэд зориулсан бэ. NULL/хоосон = бүгд. Утга: hoa_mgmt, resident, apartment, general';

-- Зөвхөн зөвшөөрөгдсөн утга орохыг баталгаажуулна
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'marketing_campaigns_target_types_chk'
  ) THEN
    ALTER TABLE marketing_campaigns
      ADD CONSTRAINT marketing_campaigns_target_types_chk
      CHECK (
        target_types IS NULL
        OR target_types <@ ARRAY['hoa_mgmt', 'resident', 'apartment', 'general']::text[]
      );
  END IF;
END $$;

