//
// Энэ бол нэг СӨХ-д тусгай нөхцөл тавьж байгаа хэрэг БИШ — платформын
// хэмжээнд «энэ өгөгдөл жинхэнэ биш» гэж тэмдэглэж байгаа юм.
export const DEMO_SOKH_IDS = new Set<number>([
  7,    // Нарантуул СӨХ — Play-д бүртгүүлсэн туршилтын СӨХ
  2678, // Туршилтын СӨХ — Хотол демо байр (Play review-ийн demo нэвтрэлт)
]);

export const isDemoSokh = (id: number | null | undefined) =>
  id != null && DEMO_SOKH_IDS.has(Number(id));
