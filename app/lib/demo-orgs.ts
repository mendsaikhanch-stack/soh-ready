// Google Play-ийн шалгалт, дотоод demo-д зориулж үүсгэсэн байгууллагууд.
// Мөнгөний тооцоонд (нийт айл, сарын орлого, төлбөр) оруулбал платформын
// бодит үзүүлэлт гажна. Тиймээс суперадмины дэлгэцүүд эднийг тусад нь
