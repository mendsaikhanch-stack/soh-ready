/**
 * Өнөөдрийн зөвлөгөө — огнооноос хамаарсан тогтмол сонголт.
 * Нэг өдөрт бүх хэрэглэгчид ижил карт харагдана, өдөр бүр солигдоно.
 */
export function getDailyCard(date = new Date()): AdviceCard {
  const key = `${date.getFullYear()}-${date.getMonth() + 1}-${date.getDate()}`;
  let hash = 0;
  for (let i = 0; i < key.length; i++) {
    hash = (hash * 31 + key.charCodeAt(i)) >>> 0;
  }
  return CARDS[hash % CARDS.length];
}
